/**
 * Environment variables the reference server and runtime read themselves.
 *
 * A connector manifest may declare operator tuning keys in
 * `runtime_requirements.tuning_environment`, and the runtime copies each
 * declared key from the server environment into that connector's child
 * process. A connector key is chosen by the connector's author, so a manifest
 * keyed `database` could otherwise declare `PDPP_DATABASE_URL`, a key inside
 * its own `PDPP_DATABASE_` namespace that the server reads for its storage
 * backend. A connector, trusted or not, must never be able to claim a name the
 * server uses. No connector list is needed to decide that: the server's own
 * configuration surface is the list.
 *
 * Every `PDPP_*` name that non-test, non-comment source under `server/`,
 * `runtime/`, `lib/` and `cli/` mentions is in the set below, except the
 * connector knobs in `undeclared-tuning-environment.ts`, which belong to their
 * connectors. `test/server-owned-environment.test.ts` scans those directories
 * and fails when the set and the source disagree, so a variable added to the
 * server must be added here in the same change.
 */
