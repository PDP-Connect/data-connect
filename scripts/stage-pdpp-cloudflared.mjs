/**
 * Downloads Cloudflare's official `cloudflared` release binary and stages it
 * as a Tauri external-binary sidecar (`src-tauri/binaries/pdpp-cloudflared-<target>[.exe]`),
 * mirroring `stage-pdpp-node.mjs`'s shape: pin a version, verify the download
 * before it touches disk under its real name, fail closed rather than ship
 * anything unverified.
 *
 * Unlike the Node sidecar (which copies the exact interpreter GitHub's own
 * `actions/setup-node` already installed and pinned by version -- nothing is
 * fetched from an arbitrary URL), there is no already-trusted local copy of
 * `cloudflared` to copy from. This script downloads Cloudflare's own GitHub
 * Release asset for the pinned tag and checks its SHA-256 against a hash
 * copied out of that same release's published notes (`TARGETS` below) --
 * never fetched live alongside the artifact, which would mean trusting the
 * download to grade its own homework.
 *
 * GOTCHA, confirmed by hand against the real 2026.9.1 release, do not
 * "simplify" this away: Cloudflare's published checksums for the two macOS
 * assets are computed over the *extracted* `cloudflared` binary, not the
 * `.tgz` archive GitHub actually serves. Hashing the downloaded `.tgz`
 * directly against the published value fails every time on macOS even
 * though the download is completely intact -- this was verified directly:
 * downloading `cloudflared-darwin-arm64.tgz` and hashing the archive itself
 * produces `c27ab8fd...`, not the published `9a0b19f6...`; only hashing the
 * `cloudflared` file after `tar -xz` matches. Linux and Windows assets are
 * raw binaries with no archive step, and verify directly.
 */

import { createHash } from "node:crypto"
import {
  chmodSync,
  copyFileSync,
  mkdirSync,
  renameSync,
  statSync,
  writeFileSync,
} from "node:fs"
import { gunzipSync } from "node:zlib"
import { dirname, join, resolve } from "node:path"
import { fileURLToPath } from "node:url"
import { isMainModule } from "./is-main-module.js"

const __dirname = dirname(fileURLToPath(import.meta.url))
const ROOT = join(__dirname, "..")

export const CLOUDFLARED_VERSION = "2026.9.1"

/**
 * One entry per Tauri target triple this app builds for (`release.yml`'s
 * build matrix). `asset` is the exact GitHub Release asset filename for
 * `CLOUDFLARED_VERSION`; `archive: "tgz"` marks the two macOS assets that
 * need extracting before the checksum in `RELEASE_CHECKSUMS` will match.
 * `sha256` is the checksum published in the corresponding GitHub Release's
 * notes (https://github.com/cloudflare/cloudflared/releases/tag/2026.9.1),
 * copied by hand and independently re-verified against a fresh download of
 * every asset below -- not generated by this script, and must be re-copied
 * by hand (never auto-fetched) if `CLOUDFLARED_VERSION` is ever bumped.
 */
export const TARGETS = new Map([
  [
    "x86_64-unknown-linux-gnu",
    {
      asset: "cloudflared-linux-amd64",
      archive: null,
      sha256:
        "03f1f25d1cc93b9ad6c60569d44060bc4f17ed97075760ed8cfca4b12dcd68cc",
    },
  ],
  [
    "aarch64-unknown-linux-gnu",
    {
      asset: "cloudflared-linux-arm64",
      archive: null,
      sha256:
        "3d97437c71848bd8df68041e12436b484a661d95073ea1937f01a845ce88faa3",
    },
  ],
  [
    "aarch64-apple-darwin",
    {
      asset: "cloudflared-darwin-arm64.tgz",
      archive: "tgz",
      sha256:
        "9a0b19f67dc7a3011bc6b972c7ce06a5fcea8784ac6bd599ffa382ea4aeb5a6e",
    },
  ],
  [
    "x86_64-apple-darwin",
    {
      asset: "cloudflared-darwin-amd64.tgz",
      archive: "tgz",
      sha256:
        "1ea07ae775b03236bd6be18ca1848d6bdc4af2f4f3bce398823b5a36e5761b75",
    },
  ],
  [
    "x86_64-pc-windows-msvc",
    {
      asset: "cloudflared-windows-amd64.exe",
      archive: null,
      sha256:
        "2837888cc0f5d58f15b6dc478376de90b4d3ba5241c7947455d1e0a0df429712",
    },
  ],
])

function fail(message) {
  throw new Error(message)
}

export function sidecarFilename(target) {
  const entry = TARGETS.get(target)
  if (!entry) fail(`Unsupported cloudflared sidecar target: ${target}`)
  const windows = target.includes("windows")
  return `pdpp-cloudflared-${target}${windows ? ".exe" : ""}`
}

function releaseAssetUrl(asset) {
  return `https://github.com/cloudflare/cloudflared/releases/download/${CLOUDFLARED_VERSION}/${asset}`
}

async function downloadToBuffer(url) {
  const response = await fetch(url)
  if (!response.ok) {
    fail(`Failed to download ${url}: HTTP ${response.status}`)
  }
  return Buffer.from(await response.arrayBuffer())
}

function sha256Hex(buffer) {
  return createHash("sha256").update(buffer).digest("hex")
}

/**
 * Extracts the single `cloudflared` binary from a gzipped tarball. Cloudflare's
 * macOS release assets contain exactly one entry (`cloudflared`) at the
 * archive root -- confirmed with `tar -tzf` against the real 2026.9.1
 * assets -- so this does not need general archive traversal, only enough to
 * pull that one file back out.
 */
function extractTarGzEntry(buffer, entryName) {
  const tarBuffer = gunzipSync(buffer)
  let offset = 0
  while (offset + 512 <= tarBuffer.length) {
    const header = tarBuffer.subarray(offset, offset + 512)
    if (header.every(byte => byte === 0)) break
    const name = header
      .subarray(0, 100)
      .toString("utf8")
      .replace(/\0.*$/s, "")
    const sizeOctal = header
      .subarray(124, 136)
      .toString("utf8")
      .replace(/\0.*$/s, "")
      .trim()
    const size = Number.parseInt(sizeOctal, 8)
    const dataStart = offset + 512
    if (name === entryName) {
      return tarBuffer.subarray(dataStart, dataStart + size)
    }
    const blocks = Math.ceil(size / 512)
    offset = dataStart + blocks * 512
  }
  fail(`Entry ${entryName} not found in tar archive`)
}

/**
 * Downloads, verifies, and stages one target's `cloudflared` sidecar.
 * `fetchImpl`/`extract` are injection points for tests -- no real network
 * access or gzip/tar decoding in unit tests, same reasoning as
 * `stagePdppNode`'s `source`/`sourceLicense` injection.
 */
export async function stagePdppCloudflared({
  target,
  projectRoot = ROOT,
  fetchBuffer = downloadToBuffer,
  extract = extractTarGzEntry,
}) {
  const entry = TARGETS.get(target)
  if (!entry) fail(`Unsupported cloudflared sidecar target: ${target}`)

  const url = releaseAssetUrl(entry.asset)
  const downloaded = await fetchBuffer(url)

  let binary
  if (entry.archive === "tgz") {
    binary = extract(downloaded, "cloudflared")
    const actual = sha256Hex(binary)
    if (actual !== entry.sha256) {
      fail(
        `Checksum mismatch for the cloudflared binary extracted from ${entry.asset}: expected ${entry.sha256}, got ${actual}. Refusing to stage an unverified binary.`
      )
    }
  } else {
    const actual = sha256Hex(downloaded)
    if (actual !== entry.sha256) {
      fail(
        `Checksum mismatch for ${entry.asset}: expected ${entry.sha256}, got ${actual}. Refusing to stage an unverified binary.`
      )
    }
    binary = downloaded
  }

  const destination = resolve(
    projectRoot,
    "src-tauri",
    "binaries",
    sidecarFilename(target)
  )
  mkdirSync(dirname(destination), { recursive: true })
  // Stage under a temp name in the same directory, then rename into place --
  // a mid-write crash or a concurrent CI cache restore must never leave a
  // partially-written file at the name the app will actually try to spawn.
  const tempDestination = `${destination}.download-${process.pid}`
  writeFileSync(tempDestination, binary)
  if (!target.includes("windows")) {
    chmodSync(tempDestination, 0o755)
  }
  renameSync(tempDestination, destination)

  if (!target.includes("windows") && (statSync(destination).mode & 0o111) === 0) {
    fail(`Staged cloudflared sidecar is not executable: ${destination}`)
  }

  // The Apache-2.0 text itself is static (vendored at
  // src-tauri/vendor-licenses/cloudflared-LICENSE, committed -- it does not
  // change release to release the way the binary does), so this is a plain
  // copy, not a download-and-verify step like the binary above.
  const licenseSource = resolve(
    projectRoot,
    "src-tauri",
    "vendor-licenses",
    "cloudflared-LICENSE"
  )
  const licenseDestination = resolve(
    projectRoot,
    "src-tauri",
    "binaries",
    "pdpp-cloudflared-LICENSE"
  )
  copyFileSync(licenseSource, licenseDestination)

  return {
    executable: destination,
    license: licenseDestination,
    version: CLOUDFLARED_VERSION,
  }
}

export function parseArgs(argv) {
  const args = {}
  for (let index = 0; index < argv.length; index += 1) {
    if (argv[index] === "--target") {
      args.target = argv[index + 1]
      index += 1
    } else {
      fail(`Unknown argument: ${argv[index]}`)
    }
  }
  if (!args.target) fail("Usage: --target <triple>")
  return args
}

if (isMainModule(import.meta.url, process.argv[1])) {
  const staged = await stagePdppCloudflared(parseArgs(process.argv.slice(2)))
  console.log(
    `Staged cloudflared ${staged.version} as ${staged.executable}`
  )
}
